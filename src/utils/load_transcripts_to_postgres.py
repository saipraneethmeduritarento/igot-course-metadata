import json
import os

import psycopg2
from dotenv import load_dotenv
from psycopg2 import sql
from psycopg2.extensions import make_dsn, parse_dsn
from psycopg2.extras import execute_values

CREATE_SQL = """
CREATE TABLE public.resource_transcripts (
    resource_id              TEXT PRIMARY KEY,
    name                     TEXT,
    course_id                TEXT,
    course_name              TEXT,
    status                   TEXT,
    mime_type                TEXT,
    duration_in_sec          INTEGER,
    latest_created_timestamp TIMESTAMPTZ,
    chunk_count              INTEGER,
    video_transcript         TEXT,
    source_languages         TEXT[],
    source_language          TEXT,
    audio_transcript         TEXT,

    -- Resource metadata generated by src/resource_metadata/extraction.py.
    -- One column per field of ResourceMetadata (src/resource_metadata/schema.py).
    course_summary              TEXT,
    description                 TEXT,
    learning_outcomes           JSONB,
    presenters                  JSONB,
    keywords                    JSONB,
    reference_resources         JSONB,
    learning_level              JSONB,
    learning_mode               JSONB,
    prerequisites               JSONB,
    bloom_taxonomy              JSONB,
    primary_competency_area     JSONB,
    behavioural_competencies    JSONB,
    functional_competencies     JSONB,
    domain_competencies         JSONB,
    sto_level                   JSONB,
    responsibilities_addressed  JSONB,
    activities_enabled          JSONB,
    target_employee_groups      JSONB,
    target_roles                JSONB,
    target_roles_exclusions     JSONB
)
"""

INSERT_SQL = """
INSERT INTO public.resource_transcripts (
    resource_id, name, course_id, course_name, status, mime_type,
    duration_in_sec, latest_created_timestamp, chunk_count,
    video_transcript, source_languages, source_language, audio_transcript
) VALUES %s
"""


def create_database(dsn):
    """Create the target database if it doesn't exist yet."""
    params = parse_dsn(dsn)
    dbname = params.get("dbname")
    if not dbname:
        return
    admin = psycopg2.connect(make_dsn(dsn, dbname="postgres"))
    admin.autocommit = True
    try:
        with admin.cursor() as cur:
            cur.execute("SELECT 1 FROM pg_database WHERE datname = %s", (dbname,))
            if not cur.fetchone():
                cur.execute(sql.SQL("CREATE DATABASE {}").format(sql.Identifier(dbname)))
                print(f"Created database {dbname}.")
    finally:
        admin.close()


def load_transcripts_to_postgres(json_path, batch_size=500):
    """Create public.resource_transcripts and load the JSON file. Skips if the table exists."""
    load_dotenv()
    dsn = os.environ["DB_DSN"]
    create_database(dsn)
    conn = psycopg2.connect(dsn)
    try:
        with conn, conn.cursor() as cur:
            cur.execute("SELECT to_regclass('public.resource_transcripts')")
            if cur.fetchone()[0]:
                print("Table public.resource_transcripts already exists - skipping.")
                return 0
            cur.execute(CREATE_SQL)

            with open(json_path, encoding="utf-8") as f:
                records = json.load(f)

            def to_int(v):
                return int(v) if v not in (None, "") else None

            def to_row(r):
                langs = r["source_language"]
                ts = r["latest_created_timestamp"]
                return (
                    r["resource_id"], r["name"], r["course_id"], r["course_name"],
                    r["status"], r["mimeType"], to_int(r["duration_in_sec"]),
                    None if not ts or ts.startswith("0001-01-01") else ts,
                    to_int(r["chunk_count"]), r["video_transcript"],
                    langs, langs[0] if langs else None, r["audio_transcript"],
                )

            for i in range(0, len(records), batch_size):
                execute_values(cur, INSERT_SQL, [to_row(r) for r in records[i:i + batch_size]])
            print(f"Inserted {len(records)} rows into public.resource_transcripts.")
            return len(records)
    finally:
        conn.close()


if __name__ == "__main__":
    load_transcripts_to_postgres("data/input/resource_transcripts.json")
